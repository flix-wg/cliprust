//! Reading the system clipboard into a [`Capture`] and writing items back.

use std::fmt;

use clipboard_rs::{Clipboard, ClipboardContent, ContentFormat};

use crate::model::{Capture, Kind, Rep, format};
use crate::{Error, Result};

#[cfg(target_os = "macos")]
mod types {
    pub const TEXT_TYPE: &str = "public.utf8-plain-text";
    pub const FILE_TYPE: &str = "public.file-url";
    pub const HTML_TYPE: &str = "public.html";
    pub const IMAGE_TYPES: &[&str] = &["public.png", "public.tiff", "public.jpeg"];
    pub const SOURCE_URL_TYPES: &[&str] = &["org.chromium.source-url"];
    pub const FIREFOX_CUSTOM_TYPE: &str = "org.mozilla.custom-clipdata";
}

#[cfg(not(target_os = "macos"))]
mod types {
    pub const TEXT_TYPE: &str = "text/plain;charset=utf-8";
    pub const FILE_TYPE: &str = "text/uri-list";
    pub const HTML_TYPE: &str = "text/html";
    pub const IMAGE_TYPES: &[&str] = &["image/png", "image/jpeg"];
    pub const SOURCE_URL_TYPES: &[&str] = &["chromium/x-source-url"];
    pub const FIREFOX_CUSTOM_TYPE: &str = "application/x-moz-custom-clipdata";
}

pub use types::{FILE_TYPE, IMAGE_TYPES, TEXT_TYPE};

const MAX_SOURCE_URL_BYTES: usize = 8 * 1024;
/// Set by the optional Firefox extension in `extensions/firefox`.
const EXTENSION_SOURCE_TYPE: &str = "text/x-cliprust-source";
const MAX_FIREFOX_CUSTOM_BYTES: usize = 256 * 1024;

/// Markers from nspasteboard.org that password managers and other apps set
/// on content that must not be recorded.
pub const PRIVATE_MARKERS: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Skipped {
    Paused,
    Empty,
    Private,
    Excluded(String),
    Unsupported(String),
    TooLarge(usize),
    Unreadable(String),
}

impl fmt::Display for Skipped {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Skipped::Paused => f.write_str("recording is paused"),
            Skipped::Empty => f.write_str("clipboard is empty"),
            Skipped::Private => f.write_str("content is marked concealed or transient"),
            Skipped::Excluded(app) => write!(f, "{app} is excluded"),
            Skipped::Unsupported(ty) => write!(f, "unsupported type {ty}"),
            Skipped::TooLarge(n) => write!(f, "{n} bytes is over the size limit"),
            Skipped::Unreadable(e) => write!(f, "could not read clipboard: {e}"),
        }
    }
}

/// Reads the current clipboard. Files win over text, text over HTML-only
/// content, and that over images,
/// because apps such as spreadsheets attach a rendered image to copied text.
pub fn read(ctx: &impl Clipboard, max_bytes: usize) -> std::result::Result<Capture, Skipped> {
    let formats = ctx
        .available_formats()
        .map_err(|e| Skipped::Unreadable(e.to_string()))?;
    if formats.is_empty() {
        return Err(Skipped::Empty);
    }
    if formats
        .iter()
        .any(|f| PRIVATE_MARKERS.contains(&f.as_str()))
    {
        return Err(Skipped::Private);
    }
    let has = |ty: &str| formats.iter().any(|f| f == ty);

    let files = ctx
        .has(ContentFormat::Files)
        .then(|| ctx.get_files().ok())
        .flatten()
        .filter(|files| !files.is_empty());
    let text = || {
        ctx.has(ContentFormat::Text)
            .then(|| ctx.get_text().ok())
            .flatten()
            .filter(|t| !t.trim().is_empty())
    };

    let mut cap = if let Some(files) = files {
        Capture {
            kind: Kind::File,
            base_uniform_type: FILE_TYPE.to_owned(),
            reps: vec![Rep::new(format::FILES, files.join("\n").into_bytes())],
            app: None,
            source_url: None,
            source_title: None,
            secret: None,
        }
    } else if let Some(text) = text() {
        let mut cap = Capture::from_text(text);
        if ctx.has(ContentFormat::Rtf)
            && let Ok(rtf) = ctx.get_rich_text()
        {
            cap.reps.push(Rep::new(format::RTF, rtf.into_bytes()));
        }
        if ctx.has(ContentFormat::Html)
            && let Ok(html) = ctx.get_html()
        {
            cap.reps.push(Rep::new(format::HTML, html.into_bytes()));
        }
        cap
    } else if let Some(html) = ctx
        .has(ContentFormat::Html)
        .then(|| ctx.get_html().ok())
        .flatten()
        .filter(|h| !h.trim().is_empty())
    {
        Capture {
            kind: Kind::Text,
            reps: vec![Rep::new(format::HTML, html.into_bytes())],
            base_uniform_type: types::HTML_TYPE.to_owned(),
            app: None,
            source_url: None,
            source_title: None,
            secret: None,
        }
    } else if let Some((ty, data)) = IMAGE_TYPES
        .iter()
        .filter(|ty| has(ty))
        .find_map(|ty| ctx.get_buffer(ty).ok().map(|data| (*ty, data)))
    {
        Capture {
            kind: Kind::Image,
            base_uniform_type: ty.to_owned(),
            reps: vec![Rep::new(ty, data)],
            app: None,
            source_url: None,
            source_title: None,
            secret: None,
        }
    } else {
        return Err(Skipped::Unsupported(formats[0].clone()));
    };

    let size: usize = cap.reps.iter().map(|r| r.data.len()).sum();
    if size > max_bytes {
        return Err(Skipped::TooLarge(size));
    }
    let buffer = |ty: &str, max: usize| {
        has(ty)
            .then(|| ctx.get_buffer(ty).ok())
            .flatten()
            .filter(|bytes| bytes.len() <= max)
    };
    let clean = |url: String| {
        Some(url.trim_end_matches('\0').trim().to_owned())
            .filter(|url| !url.is_empty() && url.len() <= MAX_SOURCE_URL_BYTES)
    };
    cap.source_url = types::SOURCE_URL_TYPES
        .iter()
        .find_map(|ty| buffer(ty, MAX_SOURCE_URL_BYTES))
        .and_then(|bytes| String::from_utf8(bytes).ok())
        .and_then(clean)
        .or_else(|| {
            buffer(types::FIREFOX_CUSTOM_TYPE, MAX_FIREFOX_CUSTOM_BYTES)
                .and_then(|bytes| firefox_custom_data(&bytes, EXTENSION_SOURCE_TYPE))
                .and_then(clean)
                .filter(|url| url.starts_with("https://") || url.starts_with("http://"))
        });
    Ok(cap)
}

/// Finds `mime` in the data Firefox writes for custom types set through
/// `clipboardData.setData`: records of a big-endian u32 kind (1 = string,
/// 0 = end), then the type and the value, each a big-endian u32 byte length
/// followed by UTF-16LE text.
fn firefox_custom_data(mut data: &[u8], mime: &str) -> Option<String> {
    fn take<'a>(data: &mut &'a [u8], n: usize) -> Option<&'a [u8]> {
        let (head, rest) = data.split_at_checked(n)?;
        *data = rest;
        Some(head)
    }
    fn u32_be(data: &mut &[u8]) -> Option<usize> {
        Some(u32::from_be_bytes(take(data, 4)?.try_into().ok()?) as usize)
    }
    fn string(data: &mut &[u8]) -> Option<String> {
        let len = u32_be(data)?;
        let units: Vec<u16> = take(data, len)?
            .as_chunks::<2>()
            .0
            .iter()
            .map(|c| u16::from_le_bytes(*c))
            .collect();
        String::from_utf16(&units).ok()
    }
    while u32_be(&mut data)? == 1 {
        let ty = string(&mut data)?;
        let value = string(&mut data)?;
        if ty == mime {
            return Some(value);
        }
    }
    None
}

/// Puts an item back on the clipboard. `plain_text` writes only the text.
/// Marks a pasteboard item as a password, so clipboard managers skip it.
pub const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";

/// Writes a revealed key as plain text marked concealed, in one item, so no
/// reader sees the value without the marker.
pub fn write_secret(ctx: &impl Clipboard, value: &str) -> Result<()> {
    ctx.set(vec![
        ClipboardContent::Other(CONCEALED_TYPE.to_owned(), Vec::new()),
        ClipboardContent::Text(value.to_owned()),
    ])
    .map_err(|e| Error::Clipboard(e.to_string()))
}

pub fn write(ctx: &impl Clipboard, reps: &[Rep], plain_text: bool) -> Result<()> {
    let contents: Vec<ClipboardContent> = reps
        .iter()
        .filter(|rep| !plain_text || rep.format == format::TEXT)
        .map(|rep| {
            let text = || String::from_utf8_lossy(&rep.data).into_owned();
            match rep.format.as_str() {
                format::TEXT => ClipboardContent::Text(text()),
                format::RTF => ClipboardContent::Rtf(text()),
                format::HTML => ClipboardContent::Html(text()),
                format::FILES => {
                    ClipboardContent::Files(text().lines().map(str::to_owned).collect())
                }
                other => ClipboardContent::Other(other.to_owned(), rep.data.clone()),
            }
        })
        .collect();
    if contents.is_empty() {
        return Err(Error::Clipboard("item has no text to paste".into()));
    }
    ctx.set(contents)
        .map_err(|e| Error::Clipboard(e.to_string()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_a_custom_type_from_firefox_clipdata() {
        // What Zen wrote for a copy with the extension in `extensions/firefox`.
        let hex = "000000010000002c74006500780074002f0078002d0063006c006900700072007500730074002d00\
                   73006f0075007200630065000000005268007400740070003a002f002f003100320037002e003000\
                   2e0030002e0031003a0038003700360035002f0069006e006400650078002e00680074006d006c00\
                   3f0071003d0031002300660072006100670000000000";
        let bytes: Vec<u8> = (0..hex.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).unwrap())
            .collect();
        assert_eq!(
            firefox_custom_data(&bytes, EXTENSION_SOURCE_TYPE).as_deref(),
            Some("http://127.0.0.1:8765/index.html?q=1#frag")
        );
        assert_eq!(firefox_custom_data(&bytes, "text/x-other"), None);
        assert_eq!(
            firefox_custom_data(&bytes[..40], EXTENSION_SOURCE_TYPE),
            None
        );
    }
}
